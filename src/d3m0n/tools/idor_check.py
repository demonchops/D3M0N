"""Cross-session access-control comparison — IDOR/BAC leads, not verdicts.

Takes ONE resource URL (one you already saw while recon'ing as your
primary session, D3M0N_SESSION_HEADERS) and requests that EXACT same URL
three ways: as your primary session ("A"), as a second configured test
account (D3M0N_SESSION_HEADERS_B, "B"), and with no session at all
(anonymous). Returns all three responses side by side — status, length,
a redacted snippet, and how similar B's body is to A's — for the agent
(and you) to reason about whether B, a different account, is seeing A's
own data. This tool never decides "this is IDOR"; like everything else
in this registry, it gathers evidence and leaves the verdict and any
actual exploitation to a human.

Bounded the same way recon.py's http_probe is, and for the same reason: a
query string lets the caller embed an arbitrary value, so without a
restriction this would be a second GET-based request-tampering primitive
(an adversarial review already found and closed exactly that hole in
http_probe once — see its docstring/tests). `_validate_identifier_shaped`
refuses anything in the path/query that isn't a plain resource-reference
character ONCE FULLY PERCENT-DECODED — checking the decoded form, not the
raw string, specifically so a payload can't hide from the character check
by percent-encoding itself (the same category of mistake as the
DOCTYPE/ENTITY guard being bypassable via UTF-16 before that got fixed:
check the effective content, not one particular encoding of it).

Needs D3M0N_SESSION_HEADERS (session A) configured — without a real
session on at least one side there's nothing to compare. Missing
D3M0N_SESSION_HEADERS_B degrades to a two-way (A vs anonymous) comparison
with a note instead of refusing outright, since "does this even require
auth" is itself a useful data point.

Optional `enumerate_range`: the standard IDOR technique of also probing
NEARBY numeric IDs under session B — if /orders/4471 is the given URL,
also try 4470, 4472, etc. The new IDs are generated by integer arithmetic
on a numeric value already found (and already validated) in the given
URL, never accepted as a new string from the caller, so this can't reopen
the request-tampering question the base tool already closed — but each
generated URL is re-validated anyway before being requested, rather than
trusting the substitution code to be bug-free. Capped at
MAX_ENUMERATE_RANGE either side and paced with a small delay between
requests, so this can't turn into a rapid-fire scrape of a real target.
Enumeration always probes via GET regardless of the base call's `method`
(see below) — breadth-first discovery of which nearby ids respond, never
repeated mutation.

`method` defaults to GET. HEAD/OPTIONS are allowed with no extra gate,
since neither can change anything (OPTIONS also surfaces the response's
`Allow` header when present — useful on its own: "can B even PATCH this
resource" without ever sending the PATCH). POST/PUT/PATCH/DELETE are a
different risk tier: replaying one under session B isn't just reading
B's view of A's data anymore, it's B actually creating/modifying/deleting
it — a real side effect caused by the test itself, same category of
mistake as the request-tampering hole once found in http_probe, except
state-changing instead of read-only. So those four need
D3M0N_ALLOW_MUTATING_IDOR_CHECKS=1 set by the human operator before the
run starts — the same kind of explicit, pre-run, config-only gate as
scope.json's `authorized: true` — rather than being a choice the agent
can make for itself mid-run. Off by default; refused with a clear error
(not silently downgraded to GET) when a mutating method is requested
without it. `body`/`content_type` ride along for POST/PUT/PATCH/DELETE,
capped at MAX_BODY_CHARS.
"""

from __future__ import annotations

import difflib
import re
import time
from urllib.parse import parse_qsl, unquote, urlencode, urlparse, urlsplit, urlunsplit

import requests

from d3m0n.config import SETTINGS

_SAFE_DECODED_RE = re.compile(r"^[A-Za-z0-9/_.\-~:=&?,]*$")
_SNIPPET_LEN = 300
_NUMERIC_RE = re.compile(r"^\d+$")
MAX_ENUMERATE_RANGE = 10
_ENUMERATE_DELAY_S = 0.3

# GET/HEAD/OPTIONS can't change anything on the server, so they need no
# extra gate. POST/PUT/PATCH/DELETE can — see the module docstring.
_SAFE_METHODS = {"GET", "HEAD", "OPTIONS"}
_MUTATING_METHODS = {"POST", "PUT", "PATCH", "DELETE"}
_ALL_METHODS = _SAFE_METHODS | _MUTATING_METHODS
MAX_BODY_CHARS = 20_000


def _fully_unquote(s: str, max_rounds: int = 5) -> str:
    """Repeatedly percent-decode (bounded) so a double/triple-encoded
    payload can't dodge the character check below by wrapping itself in
    an extra layer of %XX escapes."""
    for _ in range(max_rounds):
        decoded = unquote(s)
        if decoded == s:
            return decoded
        s = decoded
    return s


def _validate_identifier_shaped(url: str) -> str | None:
    """None if `url`'s path+query, once fully percent-decoded, contains
    only plain resource-reference characters; an error string otherwise."""
    parsed = urlparse(url)
    if parsed.fragment:
        return "idor_check refuses a target with a fragment."
    remainder = parsed.path + (("?" + parsed.query) if parsed.query else "")
    decoded = _fully_unquote(remainder)
    if not _SAFE_DECODED_RE.match(decoded):
        return (
            "idor_check refuses this target: its path/query, once decoded, contains "
            "something other than plain resource-reference characters (letters, digits, "
            "/ _ . - ~ : = & ? ,). This tool substitutes sessions for an already-known "
            "resource reference, not arbitrary payload delivery — use burp_scan/"
            "nuclei_scan/burp_traffic_review for anything that needs a crafted parameter "
            "value."
        )
    return None


def _find_numeric_id(url: str):
    """Find a numeric path segment or id-shaped query value in `url`.

    Returns (original_int_value, substitute) where substitute(new_int)
    returns a new full URL with just that one value replaced and
    everything else unchanged, or None if nothing enumerable was found.
    Prefers the LAST numeric path segment (most RESTful APIs put the
    specific resource's own id last, e.g. /api/users/12/orders/4471 ->
    4471); falls back to a query value whose key looks id-shaped (exactly
    "id", or ending in "_id"/"-id" — deliberately not a bare "id" suffix,
    so "valid"/"invalid" don't false-match) and is purely numeric.
    """
    parts = urlsplit(url)
    segments = parts.path.split("/")

    numeric_path_indices = [i for i, seg in enumerate(segments) if _NUMERIC_RE.match(seg)]
    if numeric_path_indices:
        idx = numeric_path_indices[-1]
        original = int(segments[idx])

        def substitute(new_value: int, _idx=idx, _segments=segments, _parts=parts) -> str:
            new_segments = list(_segments)
            new_segments[_idx] = str(new_value)
            new_path = "/".join(new_segments)
            return urlunsplit((_parts.scheme, _parts.netloc, new_path, _parts.query, ""))

        return original, substitute

    query_pairs = parse_qsl(parts.query, keep_blank_values=True)
    for i, (key, value) in enumerate(query_pairs):
        key_l = key.lower()
        is_id_key = key_l == "id" or key_l.endswith("_id") or key_l.endswith("-id")
        if is_id_key and _NUMERIC_RE.match(value):
            original = int(value)

            def substitute(new_value: int, _i=i, _pairs=query_pairs, _parts=parts) -> str:
                new_pairs = list(_pairs)
                new_pairs[_i] = (new_pairs[_i][0], str(new_value))
                return urlunsplit(
                    (_parts.scheme, _parts.netloc, _parts.path, urlencode(new_pairs), "")
                )

            return original, substitute

    return None


def _redact_sessions(text: str) -> str:
    """Strip any configured session-header value (either account) from
    `text` — same defense-in-depth pattern as fuzz.py's/vuln.py's/
    burp_scanner.py's redaction helpers."""
    secret_values = [
        v for v in {**SETTINGS.session_headers, **SETTINGS.session_headers_b}.values() if v
    ]
    for value in secret_values:
        text = text.replace(value, "***REDACTED-SESSION-HEADER***")
    return text


def _fetch(
    url: str,
    headers: dict[str, str] | None,
    method: str = "GET",
    body: str | None = None,
    content_type: str | None = None,
) -> dict:
    try:
        if method == "GET":
            resp = requests.get(url, timeout=10, allow_redirects=True, headers=headers or None)
        else:
            req_headers = dict(headers or {})
            data = None
            if body is not None:
                data = body.encode("utf-8")
                req_headers.setdefault("Content-Type", content_type or "application/json")
            resp = requests.request(
                method,
                url,
                data=data,
                timeout=10,
                allow_redirects=True,
                headers=req_headers or None,
            )
    except requests.RequestException as exc:
        return {"error": _redact_sessions(str(exc))}
    response_body = resp.text
    result = {
        "status": resp.status_code,
        "length": len(response_body),
        "snippet": _redact_sessions(response_body[:_SNIPPET_LEN]),
    }
    allow_header = resp.headers.get("Allow")
    if allow_header:
        result["allow_header"] = allow_header
    return result


def _enumerate_nearby(url: str, original_snippet: str, session_b: dict, enumerate_range: int) -> dict:
    """Probe up to `enumerate_range` IDs either side of `url`'s numeric id
    under session B, comparing each body to `original_snippet` (session
    A's view of the ORIGINAL id — the one reference we have for what real
    owner data looks like)."""
    found = _find_numeric_id(url)
    if found is None:
        return {"note": "No numeric path segment or id-shaped query value found to enumerate."}
    original_value, substitute = found

    clamped = max(0, min(enumerate_range, MAX_ENUMERATE_RANGE))
    probes = []
    for offset in range(-clamped, clamped + 1):
        if offset == 0:
            continue  # the original id is already covered by the main comparison
        new_value = original_value + offset
        if new_value < 0:
            continue
        candidate_url = substitute(new_value)
        # Re-validate every generated URL rather than trust the
        # substitution code is bug-free — cheap, and exactly the kind of
        # check the review taught this project not to skip.
        if _validate_identifier_shaped(candidate_url):
            continue
        time.sleep(_ENUMERATE_DELAY_S)
        probe_result = _fetch(candidate_url, session_b)
        if "error" not in probe_result and original_snippet:
            probe_result["similarity_to_original"] = round(
                difflib.SequenceMatcher(
                    None, original_snippet, probe_result["snippet"]
                ).quick_ratio(),
                3,
            )
        probes.append({"id": new_value, **probe_result})

    return {"probed_range": clamped, "original_id": original_value, "probes": probes}


def idor_check(
    url: str,
    enumerate_range: int = 0,
    method: str = "GET",
    body: str | None = None,
    content_type: str | None = None,
) -> dict:
    """Request `url` as session A, session B, and anonymous; return all three.

    If `enumerate_range` > 0, also probe nearby numeric ids under session
    B alone, always via GET (see module docstring) — capped at
    MAX_ENUMERATE_RANGE. `method` defaults to GET; POST/PUT/PATCH/DELETE
    are refused unless SETTINGS.allow_mutating_idor_checks is set (see
    module docstring for why).
    """
    if not url.startswith(("http://", "https://")):
        url = "https://" + url

    validation_error = _validate_identifier_shaped(url)
    if validation_error:
        return {"url": url, "error": validation_error}

    method = (method or "GET").upper()
    if method not in _ALL_METHODS:
        return {
            "url": url,
            "error": f"idor_check does not support method {method!r}. Supported: "
            f"{', '.join(sorted(_ALL_METHODS))}.",
        }
    if method in _MUTATING_METHODS and not SETTINGS.allow_mutating_idor_checks:
        return {
            "url": url,
            "error": (
                f"idor_check refuses to send a {method} (state-changing) request: unlike "
                "GET/HEAD/OPTIONS, this would actually create/modify/delete data under "
                "each identity it's tried as, not just read it. That needs an explicit, "
                "pre-run human decision, not something the agent decides mid-run — set "
                "D3M0N_ALLOW_MUTATING_IDOR_CHECKS=1 before starting the run if you've "
                "decided that's acceptable for this target, then try again."
            ),
        }
    if body is not None and len(body) > MAX_BODY_CHARS:
        return {
            "url": url,
            "error": f"idor_check's body is capped at {MAX_BODY_CHARS} characters.",
        }

    session_a = SETTINGS.session_headers
    if not session_a:
        return {
            "url": url,
            "error": "D3M0N_SESSION_HEADERS (session A) is not configured — idor_check "
            "needs at least one real session to compare against. See README.",
        }

    result: dict = {
        "url": url,
        "method": method,
        "as_session_a": _fetch(url, session_a, method, body, content_type),
        "as_anonymous": _fetch(url, None, method, body, content_type),
    }

    session_b = SETTINGS.session_headers_b
    if not session_b:
        result["as_session_b"] = {
            "error": "D3M0N_SESSION_HEADERS_B not configured — only A-vs-anonymous "
            "compared. Set a second test account's session to compare A vs B."
        }
        return result

    result["as_session_b"] = _fetch(url, session_b, method, body, content_type)

    as_a, as_b = result["as_session_a"], result["as_session_b"]
    if "error" not in as_a and "error" not in as_b:
        result["a_vs_b_body_similarity"] = round(
            difflib.SequenceMatcher(None, as_a["snippet"], as_b["snippet"]).quick_ratio(), 3
        )

    if enumerate_range > 0:
        result["enumeration"] = _enumerate_nearby(
            url, as_a.get("snippet", ""), session_b, enumerate_range
        )

    return result
